// Bundles the browser code (client/app.ts, client/app.css) into public/static/build with content-hashed names and writes src/generated/assets.ts so the Worker can reference them. Run by `wrangler dev`/`wrangler deploy` (wrangler.jsonc "build") and before tests.
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { relative } from "node:path";

const outdir = "public/static/build";
rmSync(outdir, { recursive: true, force: true });
mkdirSync(outdir, { recursive: true });

const result = await build({
  entryPoints: ["client/app.ts", "client/app.css"],
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2020"],
  outdir,
  entryNames: "[name]-[hash]",
  metafile: true,
  sourcemap: false,
  // Fonts and the cursor are served as separate static files.
  external: ["/static/*"],
  logLevel: "warning",
});

const assets = {};
for (const [file, meta] of Object.entries(result.metafile.outputs)) {
  if (!meta.entryPoint) continue;
  const kind = meta.entryPoint.endsWith(".css") ? "css" : "js";
  assets[kind] = "/" + relative("public", file).split("\\").join("/");
}
if (!assets.js || !assets.css) throw new Error("client build did not produce both bundles");
mkdirSync("src/generated", { recursive: true });
writeFileSync("src/generated/assets.ts", `// Generated by scripts/build-client.mjs; do not edit.\nexport const ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`);
console.log(`client: ${assets.js} ${assets.css}`);
