// Bundles the browser code (client/app.ts, client/app.css) into public/static/build with content-hashed names and writes src/generated/assets.ts so the Worker can reference them. Run by `wrangler dev`/`wrangler deploy` (wrangler.jsonc "build") and before tests.
import { build } from "esbuild";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const outdir = "public/static/build";
mkdirSync(outdir, { recursive: true });

const result = await build({
  entryPoints: ["client/app.ts", "client/app.css"],
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2020"],
  outdir,
  entryNames: "[name]-[hash]",
  metafile: true,
  sourcemap: false,
  // Fonts and the cursor are served as separate static files.
  external: ["/static/*"],
  logLevel: "warning",
});

const assets = {};
for (const [file, meta] of Object.entries(result.metafile.outputs)) {
  if (!meta.entryPoint) continue;
  const kind = meta.entryPoint.endsWith(".css") ? "css" : "js";
  assets[kind] = "/" + relative("public", file).split("\\").join("/");
}
if (!assets.js || !assets.css) throw new Error("client build did not produce both bundles");
// The CLI is served as a static file; install.sh pins its hash so a truncated or mismatched download is refused.
const cli = readFileSync("public/static/cli/sugi");
assets.cli = "/static/cli/sugi";
assets.cliSha256 = createHash("sha256").update(cli).digest("hex");
assets.cliVersion = /SUGI_CLI_VERSION="([^"]+)"/.exec(cli.toString("utf8"))?.[1] ?? "unknown";
// Drop bundles from earlier builds.
const current = new Set(Object.keys(result.metafile.outputs).map((f) => relative(outdir, f)));
for (const f of readdirSync(outdir)) if (!current.has(f)) rmSync(join(outdir, f), { force: true });
// Only touch the manifest when it changes: `wrangler dev` watches src/ and reruns this build on every change, so an unconditional write would loop forever.
const manifest = `// Generated by scripts/build-client.mjs; do not edit.\nexport const ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`;
const target = "src/generated/assets.ts";
mkdirSync("src/generated", { recursive: true });
if (!existsSync(target) || readFileSync(target, "utf8") !== manifest) writeFileSync(target, manifest);
console.log(`client: ${assets.js} ${assets.css}`);
